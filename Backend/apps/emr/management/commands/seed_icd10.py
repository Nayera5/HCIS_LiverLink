class Command(BaseCommand):
    help = 'Seed the ICD-10 catalog with liver and transplant diagnosis codes.'

    @transaction.atomic
    def handle(self, *args, **opts):
        created = 0
        for code, description, keywords in CATALOG:
            _, is_new = Icd10Code.objects.update_or_create(
                code=code, defaults={'description': description, 'keywords': keywords})
            created += is_new
        self.stdout.write(self.style.SUCCESS(f'{len(CATALOG)} ICD-10 codes ready ({created} new).'))
